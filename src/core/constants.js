/**
 * Консервативный лимит контекстного окна по умолчанию (в токенах).
 * Даже если модель поддерживает до 1M токенов, после ~128k точность ответов
 * заметно проседает, а браузерная вкладка начинает тормозить.
 */
export const DEFAULT_CONTEXT_LIMIT = 128_000;

/**
 * Среднее количество символов на 1 токен.
 * Для чистого английского текста обычно берут 4, для кириллицы и кода — 2–2.5.
 * Значение 3 — сбалансированная эвристика для смешанных чатов (русский + код).
 */
export const CHARS_PER_TOKEN = 3;

/**
 * Фиксированный «штраф» в токенах за одно вложение (картинку, PDF или файл),
 * содержимое которого недоступно в виде текста в DOM.
 */
export const ATTACHMENT_TOKEN_ESTIMATE = 1_000;

/**
 * Пороги заполнения шкалы (в долях от 0 до 1) для смены цвета индикатора в UI.
 */
export const WARNING_THRESHOLD = 0.75;
export const DANGER_THRESHOLD = 0.9;